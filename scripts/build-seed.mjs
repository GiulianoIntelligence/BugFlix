// Writes supabase/seed.sql from the starter pack in src/questions.ts, so the
// server deals the same questions the mod plays offline. Needs Node 22.18+
// (it imports TypeScript directly). Run: npm run seed
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { STARTER_PACK } from '../src/questions.ts'

const quote = text => `'${String(text).replaceAll("'", "''")}'`

const rows = STARTER_PACK.map(question =>
  [
    quote(question.id),
    quote('starter'),
    'true',
    quote(question.category),
    question.difficulty,
    quote(question.prompt),
    `${quote(JSON.stringify(question.choices))}::jsonb`,
    question.answer,
    quote(question.quip),
  ].join(', '),
)

const sql = `-- Generated by scripts/build-seed.mjs from src/questions.ts. Do not edit by hand.
insert into public.bf_questions (id, pack, is_free, category, difficulty, prompt, choices, answer, quip)
values
${rows.map(row => `  (${row})`).join(',\n')}
on conflict (id) do update set
  pack = excluded.pack,
  is_free = excluded.is_free,
  category = excluded.category,
  difficulty = excluded.difficulty,
  prompt = excluded.prompt,
  choices = excluded.choices,
  answer = excluded.answer,
  quip = excluded.quip;
`

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url))
writeFileSync(target, sql)
console.log(`Wrote ${STARTER_PACK.length} questions to supabase/seed.sql`)
